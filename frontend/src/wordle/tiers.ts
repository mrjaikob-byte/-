/**
 * Progressive difficulty mapping.
 * Returns the pool of words for a given level.
 */
export function getTieredPool(level: number): string[] {
  // 4-letter stage: levels 1-250
  if (level <= 50) return EASY_4;
  if (level <= 150) return MEDIUM_4;
  if (level <= 250) return HARD_4;
  // 5-letter stage: levels 251-700
  if (level <= 350) return EASY_5;
  if (level <= 550) return MEDIUM_5;
  if (level <= 700) return HARD_5;
  // 6-letter stage: levels 701+
  if (level <= 800) return EASY_6;
  if (level <= 950) return MEDIUM_6;
  return HARD_6;
}

