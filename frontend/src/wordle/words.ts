// Validate (Array.from to count unicode code points)
function clean(list: string[], len: number): string[] {
  const ok: string[] = [];
  const seen = new Set<string>();
  const allowed = new Set("ابتثجحخدذرزسشصضطظعغفقكلمنهويةء".split(""));
  for (const w of list) {
    const chars = Array.from(w);
    if (chars.length !== len) continue;
    // Skip words with disallowed letters (hamza variants)
    let bad = false;
    for (const c of chars) { if (!allowed.has(c)) { bad = true; break; } }
    if (bad) continue;
    // Remove if contains plain hamza for simplicity
    if (w.includes("ء")) continue;
    if (seen.has(w)) continue;
    seen.add(w);
    ok.push(w);
  }
  return ok;
}

export const WORDS_4 = clean(rawWords4, 4);
export const WORDS_5 = clean(rawWords5, 5);
export const WORDS_6 = clean(rawWords6, 6);

export function getWordPool(level: number): string[] {
  if (level <= 250) return WORDS_4;
  if (level <= 700) return WORDS_5;
  return WORDS_6;
}

export function getWordLength(level: number): number {
  if (level <= 250) return 4;
  if (level <= 700) return 5;
  return 6;
}

// Simple deterministic hash -> index
function hashLevel(level: number, poolSize: number): number {
  // LCG-ish deterministic mixing
  let x = level * 2654435761;
  x = x ^ (x >>> 13);
  x = x * 1597334677;
  x = x ^ (x >>> 16);
  return Math.abs(x) % poolSize;
}

export function getWordForLevel(level: number): string {
  const pool = getWordPool(level);
  if (pool.length === 0) return "كلمة";
  return pool[hashLevel(level, pool.length)];
}
